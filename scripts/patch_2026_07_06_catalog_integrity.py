def _find_part(conn, brand: str, name: str) -> sqlite3.Row | None:
    """Find a part by (brand, model_name), tolerating the June-14 brand-prefix
    normalisation: prod DBs store stripped names, fresh seeds store the
    brand-prefixed originals."""
    for candidate in (name, f"{brand} {name}"):
        row = conn.execute(
            "SELECT * FROM parts WHERE brand = ? AND model_name = ? ORDER BY id LIMIT 1",
            (brand, candidate),
        ).fetchone()
        if row is not None:
            return row
    return None


def _apply_rule_fixes(conn) -> tuple[int, int, list[str]]:
    changed = 0
    noop = 0
    problems: list[str] = []
    for fix in RULE_FIXES:
        row = _find_part(conn, fix["brand"], fix["name"])
        if row is None and "rename" in fix:
            # Maybe already renamed by a prior run
            row = _find_part(conn, fix["brand"], fix["rename"])
        if row is None:
            problems.append(f"part not found: {fix['brand']} / {fix['name']}")
            continue

        updates: dict[str, object] = {}

        # fitment_rules updates
        if fix.get("set") or fix.get("desc"):
            try:
                rules = json.loads(row["fitment_rules"]) if row["fitment_rules"] else {}
            except (json.JSONDecodeError, TypeError):
                problems.append(f"invalid fitment_rules on part {row['id']}")
                continue
            match = rules.setdefault("match", {})
            dirty = False
            for k, v in (fix.get("set") or {}).items():
                if match.get(k) != v:
                    match[k] = v
                    dirty = True
            if fix.get("desc") and rules.get("description") != fix["desc"]:
                rules["description"] = fix["desc"]
                dirty = True
            if dirty:
                updates["fitment_rules"] = json.dumps(rules)

        # rename
        if "rename" in fix and row["model_name"] != fix["rename"]:
            updates["model_name"] = fix["rename"]

        if not updates:
            noop += 1
            continue

        sets = ", ".join(f"{k} = ?" for k in updates)
        conn.execute(
            f"UPDATE parts SET {sets}, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
            (*updates.values(), row["id"]),
        )
        changed += 1
    return changed, noop, problems


def _null_chain_pitches(conn) -> tuple[int, int, list[str]]:
    changed = 0
    noop = 0
    problems: list[str] = []
    for bike_id, name_frag in CHAIN_PITCH_NULL_BIKES:
        bike = conn.execute(
            "SELECT id, model_name FROM bike_models WHERE id = ?", (bike_id,)
        ).fetchone()
        if bike is None or name_frag.lower() not in bike["model_name"].lower():
            problems.append(
                f"bike {bike_id} ({name_frag}) not found / name mismatch — skipped"
            )
            continue
        rows = conn.execute(
            "SELECT id, drivetrain_params FROM bike_configs "
            "WHERE bike_model_id = ? AND is_current = 1",
            (bike_id,),
        ).fetchall()
        if not rows:
            problems.append(f"bike {bike_id} has no is_current config — skipped")
            continue
        for cfg in rows:
            try:
                dp = (
                    json.loads(cfg["drivetrain_params"])
                    if cfg["drivetrain_params"]
                    else {}
                )
            except (json.JSONDecodeError, TypeError):
                problems.append(f"config {cfg['id']} has invalid drivetrain_params")
                continue
            if dp.get("chain_pitch") is None:
                noop += 1
                continue
            dp["chain_pitch"] = None
            conn.execute(
                "UPDATE bike_configs SET drivetrain_params = ?, "
                "updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                (json.dumps(dp), cfg["id"]),
            )
            changed += 1
    return changed, noop, problems


def _merge_walbro(conn) -> tuple[int, list[str]]:
    """Merge the duplicate Walbro 450 LPH Fuel Pump rows (seed.py + the
    drag_specific catalog both seeded one). Keep the lowest id, repoint
    part_prices / sim_runs.applied_parts, widen the survivor's rule to the
    union (600cc+ 4T — a 450 LPH pump is a generic EFI drag part), delete
    the duplicate."""
    changed = 0
    problems: list[str] = []
    rows = conn.execute(
        "SELECT id, fitment_rules FROM parts "
        "WHERE brand = 'Walbro' AND model_name IN "
        "('450 LPH Fuel Pump', 'Walbro 450 LPH Fuel Pump') ORDER BY id"
    ).fetchall()
    if not rows:
        problems.append("Walbro 450 LPH not found")
        return changed, problems

    keeper = rows[0]
    # Widen the keeper to the union rule (idempotent).
    target_rules = {
        "tier": "family",
        "match": {"displacement_min_cc": 600, "stroke_type": 4},
        "description": "Walbro 450 LPH high-flow pump for 600cc+ fuel-injected "
        "bikes (merged duplicate catalog rows, 2026-07-06)",
    }
    current = json.loads(keeper["fitment_rules"]) if keeper["fitment_rules"] else {}
    if current != target_rules:
        conn.execute(
            "UPDATE parts SET fitment_rules = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
            (json.dumps(target_rules), keeper["id"]),
        )
        changed += 1

    for dup in rows[1:]:
        conn.execute(
            "UPDATE part_prices SET part_id = ? WHERE part_id = ?",
            (keeper["id"], dup["id"]),
        )
        # sim_runs.applied_parts is a JSON list of part ids
        for run in conn.execute(
            "SELECT id, applied_parts FROM sim_runs WHERE applied_parts LIKE ?",
            (f"%{dup['id']}%",),
        ).fetchall():
            try:
                ids = json.loads(run["applied_parts"])
            except (json.JSONDecodeError, TypeError):
                continue
            if isinstance(ids, list) and dup["id"] in ids:
                ids = [keeper["id"] if i == dup["id"] else i for i in ids]
                conn.execute(
                    "UPDATE sim_runs SET applied_parts = ? WHERE id = ?",
                    (json.dumps(ids), run["id"]),
                )
        conn.execute("DELETE FROM parts WHERE id = ?", (dup["id"],))
        changed += 1
    return changed, problems


def _fix_bikes(conn) -> tuple[int, int, list[str]]:
    changed = 0
    noop = 0
    problems: list[str] = []
    for bike_id, frag, column, old, new in BIKE_FIXES:
        row = conn.execute(
            f"SELECT id, model_name, {column} AS val FROM bike_models WHERE id = ?",
            (bike_id,),
        ).fetchone()
        if row is None or frag.lower() not in row["model_name"].lower():
            problems.append(
                f"bike {bike_id} ({frag}) not found / name mismatch — skipped"
            )
            continue
        if row["val"] == new:
            noop += 1
        elif row["val"] == old:
            conn.execute(
                f"UPDATE bike_models SET {column} = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                (new, bike_id),
            )
            changed += 1
        else:
            problems.append(
                f"bike {bike_id} {column} is {row['val']!r} (expected {old!r}) — skipped"
            )

    # Mirror the cylinder_config fixes into the current configs' engine_params
    # blobs (the compatibility engine enriches from bike_models first, but
    # legacy rows / the enrichment fallback read the blob).
    for bike_id, (old, new) in CYLINDER_MIRRORS.items():
        row = conn.execute(
            "SELECT bc.id, bc.engine_params FROM bike_configs bc "
            "WHERE bc.bike_model_id = ? AND bc.is_current = 1",
            (bike_id,),
        ).fetchone()
        if row is None:
            continue
        try:
            ep = json.loads(row["engine_params"]) if row["engine_params"] else {}
        except (json.JSONDecodeError, TypeError):
            ep = None
        if ep is not None and ep.get("cylinder_config") == old:
            ep["cylinder_config"] = new
            conn.execute(
                "UPDATE bike_configs SET engine_params = ?, "
                "updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                (json.dumps(ep), row["id"]),
            )
            changed += 1
        else:
            noop += 1
    return changed, noop, problems


def main() -> int:
    if not os.path.exists(DB):
        print(f"ERROR: DB not found at {DB}", file=sys.stderr)
        return 2
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")

    total_changed = 0
    all_problems: list[str] = []

    c, n, p = _null_chain_pitches(conn)
    print(f"[A] chain_pitch -> None: {c} configs updated, {n} already clean")
    total_changed += c
    all_problems += p

    c, n, p = _apply_rule_fixes(conn)
    print(f"[B/C/D/E] fitment rules: {c} parts updated, {n} already applied")
    total_changed += c
    all_problems += p

    c, p = _merge_walbro(conn)
    print(f"[E] Walbro duplicate merge: {c} changes")
    total_changed += c
    all_problems += p

    c, n, p = _fix_bikes(conn)
    print(f"[F] bike data fixes: {c} updated, {n} already applied")
    total_changed += c
    all_problems += p

    conn.commit()

    fk = conn.execute("PRAGMA foreign_key_check").fetchall()
    if fk:
        print(
            f"ERROR: foreign_key_check reported {len(fk)} violations", file=sys.stderr
        )
        return 1

    for prob in all_problems:
        print(f"  WARN: {prob}")

    print(f"Done. {total_changed} total changes. FK check clean.")
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
