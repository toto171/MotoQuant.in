#!/usr/bin/env python3
"""Regenerate web/data/bike-ids.json — the sitemap's offline fallback list.

Why this exists
---------------
`web/app/sitemap.js` fetches the live catalog from `/api/bikes` at build time.
When that fetch fails (cold Render instance, preview build with no backend,
network blip) it needs a fallback list of bike-detail routes. That fallback
used to be `Array.from({length: 600}, (_, i) => i + 1)` — a contiguous range,
on the assumption that catalog IDs are dense. They are not: reseeds have left
541 real rows scattered up to id 4637, so the range fallback omitted 198 real
bike pages and emitted 257 URLs for bikes that do not exist.

So the fallback now reads real IDs from this committed manifest.

The query below deliberately mirrors `/api/bikes` in `motoquant/api.py`
(the JOIN against `manufacturers` included) so the manifest can never contain
an ID the live API would not return.

Usage
-----
    python web/scripts/gen_bike_ids.py            # writes web/data/bike-ids.json
    python web/scripts/gen_bike_ids.py --check    # exit 1 if stale (CI-friendly)

Run it whenever the bike catalog changes — it belongs to the same ritual as
`python scripts/audit_headline_stats.py` (AGENTS.md rule 5). The database is
opened READ-ONLY; this script never writes to motoquant.db. Output is
deterministic (no timestamp), so regenerating with an unchanged catalog is a
no-op in `git diff`.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

WEB_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = WEB_DIR.parent
DEFAULT_DB = REPO_ROOT / "motoquant.db"
OUTPUT = WEB_DIR / "data" / "bike-ids.json"

# Mirrors the row query of GET /api/bikes (motoquant/api.py::list_bikes).
QUERY = """
    SELECT bm.id
      FROM bike_models bm
      JOIN manufacturers m ON bm.manufacturer_id = m.id
     ORDER BY bm.id
"""


def read_ids(db_path: Path) -> list[int]:
    if not db_path.exists():
        sys.exit(f"error: database not found at {db_path}")
    # mode=ro — this script must never mutate the catalog.
    con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    try:
        return [int(row[0]) for row in con.execute(QUERY)]
    finally:
        con.close()


def build_payload(ids: list[int]) -> dict:
    return {
        "_comment": (
            "Generated by web/scripts/gen_bike_ids.py from motoquant.db. "
            "Do not hand-edit. Offline fallback for web/app/sitemap.js; the "
            "live /api/bikes fetch remains the primary source."
        ),
        "source": "motoquant.db :: bike_models JOIN manufacturers",
        "count": len(ids),
        "ids": ids,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed manifest matches the DB; write nothing",
    )
    args = parser.parse_args()

    ids = read_ids(args.db)
    if not ids:
        sys.exit("error: query returned zero bike ids — refusing to write")

    payload = build_payload(ids)
    rendered = json.dumps(payload, indent=2) + "\n"

    if args.check:
        if not args.out.exists():
            print(f"STALE: {args.out} does not exist")
            return 1
        if args.out.read_text(encoding="utf-8") != rendered:
            existing = json.loads(args.out.read_text(encoding="utf-8"))
            print(
                f"STALE: {args.out} has {existing.get('count')} ids, "
                f"database has {len(ids)}. Re-run: python {Path(__file__).name}"
            )
            return 1
        print(f"OK: {args.out.name} in sync ({len(ids)} bike ids)")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.out} — {len(ids)} bike ids (max id {max(ids)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
