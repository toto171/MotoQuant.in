# Metrics dataclass
# ─────────────────────────────────────────────────────────────────


@dataclass
class SurrogateMetrics:
    """
    Accuracy metrics for the XGBoost surrogate evaluated on a held-out test set.

    All ET metrics are in seconds; all trap speed metrics in m/s.
    """

    # ET metrics
    et_mae_s: float  # mean absolute error
    et_rmse_s: float  # root-mean-square error
    et_r2: float  # R² coefficient of determination
    et_within_50ms: float  # fraction of predictions within ±0.050 s of truth (0–1)
    et_within_100ms: float
    et_max_error_s: float  # worst-case absolute error

    # Trap speed metrics
    trap_mae_mps: float
    trap_rmse_mps: float
    trap_r2: float
    trap_within_1kmh: float  # fraction within ±0.278 m/s (≈ 1 km/h) of truth (0–1)

    # Dataset size
    n_test: int
    inference_us: float  # microseconds per prediction (single sample)

    def print_report(self) -> None:
        """Print a formatted accuracy report to stdout."""
        tol_50 = self.et_within_50ms * 100
        tol_100 = self.et_within_100ms * 100
        t1 = self.trap_within_1kmh * 100
        trap_mae_kmh = self.trap_mae_mps * 3.6
        trap_rmse_kmh = self.trap_rmse_mps * 3.6

        print("\n" + "═" * 58)
        print("  XGBoost Surrogate — Test Set Accuracy Report")
        print("═" * 58)
        print(f"  Test samples       : {self.n_test:,}")
        print(f"  Inference latency  : {self.inference_us:.1f} µs/prediction")
        print()
        print("  ── Elapsed Time (ET) ──────────────────────────────")
        print(f"  MAE                : {self.et_mae_s * 1000:.1f} ms")
        print(f"  RMSE               : {self.et_rmse_s * 1000:.1f} ms")
        print(f"  R²                 : {self.et_r2:.4f}")
        print(f"  Within ±50 ms      : {tol_50:.1f}%")
        print(f"  Within ±100 ms     : {tol_100:.1f}%")
        print(f"  Max error          : {self.et_max_error_s * 1000:.1f} ms")
        print()
        print("  ── Trap Speed ─────────────────────────────────────")
        print(f"  MAE                : {trap_mae_kmh:.2f} km/h")
        print(f"  RMSE               : {trap_rmse_kmh:.2f} km/h")
        print(f"  R²                 : {self.trap_r2:.4f}")
        print(f"  Within ±1 km/h     : {t1:.1f}%")
        print("═" * 58)

    def to_dict(self) -> dict:
        return {
            "et_mae_ms": round(self.et_mae_s * 1000, 2),
            "et_rmse_ms": round(self.et_rmse_s * 1000, 2),
            "et_r2": round(self.et_r2, 4),
            "et_within_50ms_pct": round(self.et_within_50ms * 100, 1),
            "et_within_100ms_pct": round(self.et_within_100ms * 100, 1),
            "et_max_error_ms": round(self.et_max_error_s * 1000, 2),
            "trap_mae_kmh": round(self.trap_mae_mps * 3.6, 2),
            "trap_rmse_kmh": round(self.trap_rmse_mps * 3.6, 2),
            "trap_r2": round(self.trap_r2, 4),
            "trap_within_1kmh_pct": round(self.trap_within_1kmh * 100, 1),
            "n_test": self.n_test,
            "inference_us": round(self.inference_us, 2),
        }


# ─────────────────────────────────────────────────────────────────
# XGBSurrogate
# ─────────────────────────────────────────────────────────────────


class XGBSurrogate:
    """
    XGBoost-based surrogate for motorcycle quarter-mile prediction.

    Wraps two independent XGBRegressor models (ET + trap speed) with a
    unified fit/predict/evaluate/save/load interface.

    Parameters
    ----------
    xgb_params : dict, optional
        Override for XGBoost hyper-parameters.  Any key not provided
        falls back to ``DEFAULT_XGB_PARAMS``.
    """

    def __init__(
        self,
        xgb_params: dict | None = None,
        log_transform_et: bool = False,
    ) -> None:
        """
        Parameters
        ----------
        xgb_params       : XGBoost hyper-parameter overrides.
        log_transform_et : If True, train on log(ET) and exponentiate
                           predictions.  Rarely needed when derived features
                           (power_to_weight_hp_kg) are present — those already
                           linearise the power-law ET relationship.  Default: False.
        """
        params = {**DEFAULT_XGB_PARAMS, **(xgb_params or {})}
        try:
            from xgboost import XGBRegressor
        except ImportError as exc:
            raise ImportError(
                "XGBoost is required for the surrogate model. "
                "Install it with: pip install xgboost"
            ) from exc

        # Separate models for ET and trap speed — gives independent hyper-param tuning
        self._model_et = XGBRegressor(**params)
        self._model_trap = XGBRegressor(**params)
        self._is_fitted = False
        self._log_transform_et = log_transform_et
        self._feature_names = FEATURE_NAMES[:]  # snapshot at init
        self._n_train: int = 0
        self._train_elapsed_s: float = 0.0

    # ── Fitting ──────────────────────────────────────────────────

    def fit(
        self,
        X: np.ndarray,
        y_et: np.ndarray,
        y_trap: np.ndarray,
        eval_set_fraction: float = 0.10,
        early_stopping_rounds: int = 100,
        verbose: bool = False,
    ) -> XGBSurrogate:
        """
        Train both surrogate models.

        Parameters
        ----------
        X               : (n, 14) feature matrix
        y_et            : (n,) ET labels in seconds
        y_trap          : (n,) trap speed labels in m/s
        eval_set_fraction : fraction of data used for early stopping
        early_stopping_rounds : stop if validation loss doesn't improve
        verbose         : forward XGBoost verbose output to stderr

        Returns self for chaining.
        """
        _check_array_shapes(X, y_et, y_trap)
        t0 = time.perf_counter()

        n = len(X)
        n_val = max(1, int(n * eval_set_fraction))
        rng = np.random.default_rng(0)
        val_idx = rng.choice(n, size=n_val, replace=False)
        train_mask = np.ones(n, dtype=bool)
        train_mask[val_idx] = False

        X_tr, X_val = X[train_mask], X[val_idx]
        y_et_tr, y_et_val = y_et[train_mask], y_et[val_idx]
        y_trap_tr, y_trap_val = y_trap[train_mask], y_trap[val_idx]

        # Log-transform ET: ET ≈ k·(mass/power)^α is a power law.
        # Working in log-space linearises it, dramatically reducing MAE.
        y_et_fit = (
            np.log(y_et_tr.astype(np.float64)) if self._log_transform_et else y_et_tr
        )
        y_et_val_fit = (
            np.log(y_et_val.astype(np.float64)) if self._log_transform_et else y_et_val
        )

        fit_kwargs_et = {"eval_set": [(X_val, y_et_val_fit)], "verbose": verbose}
        fit_kwargs_tr = {"eval_set": [(X_val, y_trap_val)], "verbose": verbose}

        # Early stopping: XGBoost >=1.6 uses early_stopping_rounds in fit()
        try:
            self._model_et.fit(
                X_tr,
                y_et_fit,
                early_stopping_rounds=early_stopping_rounds,
                **fit_kwargs_et,
            )
            self._model_trap.fit(
                X_tr,
                y_trap_tr,
                early_stopping_rounds=early_stopping_rounds,
                **fit_kwargs_tr,
            )
        except TypeError:
            # Older XGBoost API: early_stopping_rounds in constructor only
            self._model_et.fit(X_tr, y_et_fit, **fit_kwargs_et)
            self._model_trap.fit(X_tr, y_trap_tr, **fit_kwargs_tr)

        self._is_fitted = True
        self._n_train = int(train_mask.sum())
        self._train_elapsed_s = time.perf_counter() - t0
        logger.info(
            "XGBSurrogate fitted on %d samples in %.1fs",
            self._n_train,
            self._train_elapsed_s,
        )
        return self

    # ── Prediction ───────────────────────────────────────────────

    def predict(self, X: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """
        Predict ET and trap speed for a feature matrix.

        Parameters
        ----------
        X : (n, 14) feature matrix

        Returns
        -------
        y_et_pred   : (n,) predicted ET in seconds
        y_trap_pred : (n,) predicted trap speed in m/s
        """
        self._check_fitted()
        X = np.atleast_2d(X).astype(np.float32)
        et_raw = self._model_et.predict(X)
        if self._log_transform_et:
            et_pred = np.exp(et_raw).astype(np.float32)
        else:
            et_pred = et_raw.astype(np.float32)
        return et_pred, self._model_trap.predict(X).astype(np.float32)

    def predict_config(self, config: BikeConfig) -> tuple[float, float]:
        """
        End-to-end prediction from a live BikeConfig.

        Parameters
        ----------
        config : BikeConfig to evaluate

        Returns
        -------
        et_s          : predicted quarter-mile ET in seconds
        trap_speed_mps : predicted trap speed in m/s
        """
        self._check_fitted()
        x = config_to_feature_vector(config).reshape(1, -1)
        et_arr, trap_arr = self.predict(x)
        return float(et_arr[0]), float(trap_arr[0])

    # ── Evaluation ───────────────────────────────────────────────

    def evaluate(
        self, X: np.ndarray, y_et: np.ndarray, y_trap: np.ndarray
    ) -> SurrogateMetrics:
        """
        Compute accuracy metrics on a held-out test set.

        Parameters
        ----------
        X      : (n, 14) feature matrix
        y_et   : (n,) true ET values in seconds
        y_trap : (n,) true trap speed values in m/s

        Returns
        -------
        SurrogateMetrics
        """
        self._check_fitted()
        _check_array_shapes(X, y_et, y_trap)

        # Time a batch of single-sample predictions for latency estimate
        t_inf_start = time.perf_counter()
        n_inf = min(200, len(X))
        for i in range(n_inf):
            self.predict(X[i : i + 1])
        inf_us = (time.perf_counter() - t_inf_start) / n_inf * 1e6

        et_pred, trap_pred = self.predict(X)
        et_err = np.abs(et_pred - y_et)
        trap_err = np.abs(trap_pred - y_trap)
        n = len(y_et)

        def r2(y_true: np.ndarray, y_pred: np.ndarray) -> float:
            ss_res = float(np.sum((y_true - y_pred) ** 2))
            ss_tot = float(np.sum((y_true - np.mean(y_true)) ** 2))
            return 1.0 - ss_res / ss_tot if ss_tot > 0 else 0.0

        return SurrogateMetrics(
            et_mae_s=float(np.mean(et_err)),
            et_rmse_s=float(np.sqrt(np.mean(et_err**2))),
            et_r2=r2(y_et, et_pred),
            et_within_50ms=float(np.mean(et_err <= 0.050)),
            et_within_100ms=float(np.mean(et_err <= 0.100)),
            et_max_error_s=float(np.max(et_err)),
            trap_mae_mps=float(np.mean(trap_err)),
            trap_rmse_mps=float(np.sqrt(np.mean(trap_err**2))),
            trap_r2=r2(y_trap, trap_pred),
            trap_within_1kmh=float(np.mean(trap_err <= (1.0 / 3.6))),
            n_test=n,
            inference_us=inf_us,
        )

    def feature_importance(self) -> dict[str, float]:
        """
        Return feature importance scores for the ET model (gain-based).

        Returns
        -------
        Dict mapping feature name → importance score, sorted descending.
        """
        self._check_fitted()
        importances = self._model_et.feature_importances_
        ranked = sorted(
            zip(self._feature_names, importances),
            key=lambda kv: kv[1],
            reverse=True,
        )
        return dict(ranked)

    # ── Persistence ──────────────────────────────────────────────

    def save(self, path: str | Path) -> None:
        """
        Serialize both XGBoost models + metadata to a .pkl file.

        Parameters
        ----------
        path : destination file path (will be created / overwritten)
        """
        import joblib  # scikit-learn dependency, always present with xgboost installs

        self._check_fitted()
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "model_et": self._model_et,
            "model_trap": self._model_trap,
            "feature_names": self._feature_names,
            "n_train": self._n_train,
            "train_elapsed_s": self._train_elapsed_s,
            "log_transform_et": self._log_transform_et,
            "version": "2.0",
        }
        joblib.dump(payload, path, compress=3)
        logger.info("XGBSurrogate saved to %s", path)

    @classmethod
    def load(cls, path: str | Path) -> XGBSurrogate:
        """
        Load a surrogate model saved by :meth:`save`.

        Parameters
        ----------
        path : path to the .pkl file

        Returns
        -------
        A fitted XGBSurrogate instance ready for prediction.
        """
        import joblib

        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(f"Surrogate model not found: {path}")
        payload = joblib.load(path)

        # Validate stored feature schema
        stored = payload.get("feature_names", [])
        if list(stored) != FEATURE_NAMES:
            warnings.warn(
                "Stored surrogate feature names differ from current FEATURE_NAMES. "
                "Model may produce incorrect predictions — consider retraining."
            )

        inst = cls.__new__(cls)
        inst._model_et = payload["model_et"]
        inst._model_trap = payload["model_trap"]
        inst._feature_names = list(payload.get("feature_names", FEATURE_NAMES))
        inst._n_train = int(payload.get("n_train", 0))
        inst._train_elapsed_s = float(payload.get("train_elapsed_s", 0.0))
        inst._log_transform_et = bool(payload.get("log_transform_et", False))
        inst._is_fitted = True
        logger.info(
            "XGBSurrogate loaded from %s (trained on %d samples)",
            path,
            inst._n_train,
        )
        return inst

    # ── Helpers ───────────────────────────────────────────────────

    def _check_fitted(self) -> None:
        if not self._is_fitted:
            raise RuntimeError(
                "XGBSurrogate is not fitted. Call fit() or load() first."
            )

    @property
    def is_fitted(self) -> bool:
        return self._is_fitted

    @property
    def n_train(self) -> int:
        """Number of training samples used to fit the model."""
        return self._n_train

    @property
    def train_elapsed_s(self) -> float:
        """Wall-clock training time in seconds."""
        return self._train_elapsed_s

    def __repr__(self) -> str:
        status = (
            f"fitted on {self._n_train:,} samples" if self._is_fitted else "not fitted"
        )
        return f"XGBSurrogate({status})"


