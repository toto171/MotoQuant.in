"""
MotoQuant — XGBoost Surrogate Model (Phase 4B)
==============================================
Baseline surrogate model that maps 14 physical bike parameters → (ET, trap speed)
using gradient-boosted trees (XGBoost).  Trained on synthetic data generated by
``surrogate_data.generate_training_data()``.

**Role in the surrogate roadmap:**
  Phase 4B (this file) — XGBoost BDT: ~50 k simulation samples, 10-minute
    training run on CPU, establishes the accuracy floor.  Target: MAE < 0.05 s.
  Phase 4A (DNN) — 4-layer MLP trained on same/larger dataset, ~1 ms GPU inference.
    Build this only if XGBoost meets the accuracy floor but not the latency target.
  Phase 4C (PINN) — Physics-Informed NN, only if DNN shows poor extrapolation.

Key design decisions
--------------------
* **Two independent XGBRegressor models** — one for ET, one for trap speed.
  Multi-output wrappers add complexity for no benefit here.
* **joblib persistence** — scikit-learn convention; stores both models + metadata
  in a single .pkl file.
* **SurrogateMetrics** — RMSE, MAE, R² on held-out test set, plus a
  ``within_50ms`` percentage (fraction of predictions within ±50 ms of truth)
  which is the target accuracy for slider-driven UI.
* **``XGBSurrogate.predict_config()``** — accepts a live BikeConfig for
  end-to-end inference in app.py / FastAPI without manual feature extraction.

Usage
-----
    from motoquant.analysis.surrogate_xgb import XGBSurrogate
    from motoquant.analysis.surrogate_data import generate_training_data
    from motoquant.defaults import gsxr1000_k5

    # One-time offline training
    ds = generate_training_data(gsxr1000_k5(), n_samples=512)
    train_ds, test_ds = ds.split(test_fraction=0.15, seed=0)

    model = XGBSurrogate()
    model.fit(*train_ds.to_arrays())
    metrics = model.evaluate(*test_ds.to_arrays())
    metrics.print_report()
    model.save("surrogate.pkl")

    # Fast inference at runtime
    model = XGBSurrogate.load("surrogate.pkl")
    et, trap = model.predict_config(gsxr1000_k5())
    print(f"ET: {et:.3f}s  trap: {trap*3.6:.1f} km/h")
"""

