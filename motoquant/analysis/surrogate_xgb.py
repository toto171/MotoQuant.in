def train_surrogate(
    dataset: SurrogateDataset,
    test_fraction: float = 0.15,
    xgb_params: dict | None = None,
    verbose: bool = False,
    seed: int = 0,
) -> tuple[XGBSurrogate, SurrogateMetrics]:
    """
    One-shot pipeline: split dataset, fit XGBSurrogate, return metrics.

    Parameters
    ----------
    dataset       : SurrogateDataset from ``generate_training_data()``
    test_fraction : fraction held out for evaluation
    xgb_params    : optional hyper-parameter overrides
    verbose       : forward XGBoost training output
    seed          : split seed

    Returns
    -------
    (model, metrics) — fitted XGBSurrogate + test set SurrogateMetrics
    """
    train_ds, test_ds = dataset.split(test_fraction=test_fraction, seed=seed)
    X_tr, y_et_tr, y_trap_tr = train_ds.to_arrays()
    X_te, y_et_te, y_trap_te = test_ds.to_arrays()

    model = XGBSurrogate(xgb_params=xgb_params)
    model.fit(X_tr, y_et_tr, y_trap_tr, verbose=verbose)
    metrics = model.evaluate(X_te, y_et_te, y_trap_te)
    return model, metrics


