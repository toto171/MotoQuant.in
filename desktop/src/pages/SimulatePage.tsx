import { useState, useEffect, useRef, useCallback } from "react";
import { Play, Loader2, AlertTriangle, Save, Check, FileDown } from "lucide-react";
import { useSimulate, useVenues, useSaveRun } from "@/hooks/useApi";
import { BikePicker } from "@/components/BikePicker";
import { StatTile } from "@/components/StatTile";
import { SimChart, SIM_CHANNELS } from "@/components/SimChart";
import { OfflineBanner } from "@/components/OfflineBanner";
import { SkeletonStatTile, SkeletonChartGrid } from "@/components/Skeleton";
import { useSettings } from "@/contexts/SettingsContext";
import { toast } from "@/store/toastStore";
import type { BikeSummary } from "@/types/api";

// PDF export — pure jsPDF, no canvas capture, generates in <200ms.
async function exportSimPdf(data: {
  bike: { manufacturer: string; model: string };
  et: number;
  trap: number;
  splits: Record<string, number>;
  config: {
    peak_power_hp: number;
    peak_torque_nm: number;
    total_mass_kg: number;
    displacement_cc: number | null;
    redline_rpm: number | null;
    gear_count: number;
    cd: number | null;
  };
}) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const W = 210;
  const margin = 18;

  // Header bar
  doc.setFillColor(249, 115, 22); // signal-500
  doc.rect(0, 0, W, 22, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("MotoQuant Pro — Simulation Report", margin, 14);

  // Bike title
  doc.setTextColor(20, 20, 30);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text(`${data.bike.manufacturer} ${data.bike.model}`, margin, 36);

  // ET hero
  doc.setFillColor(249, 115, 22);
  doc.roundedRect(margin, 42, 80, 22, 3, 3, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text("Quarter-mile ET", margin + 4, 50);
  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.text(`${data.et.toFixed(3)} s`, margin + 4, 60);

  doc.setFillColor(30, 30, 40);
  doc.roundedRect(margin + 86, 42, 80, 22, 3, 3, "F");
  doc.setTextColor(200, 200, 210);
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text("Trap speed", margin + 90, 50);
  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.text(`${data.trap.toFixed(1)} km/h`, margin + 90, 60);

  // Splits table
  doc.setTextColor(100, 100, 120);
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.text("SPLIT TIMES", margin, 76);

  const splits = [
    ["60 ft", data.splits["60ft_s"]?.toFixed(3) ?? "—"],
    ["330 ft", data.splits["330ft_s"]?.toFixed(3) ?? "—"],
    ["1/8 mile (660 ft)", data.splits["660ft_s"]?.toFixed(3) ?? "—"],
    ["1000 ft", data.splits["1000ft_s"]?.toFixed(3) ?? "—"],
    ["1320 ft (finish)", data.splits["1320ft_s"]?.toFixed(3) ?? "—"],
  ];
  let y = 82;
  splits.forEach(([label, val], i) => {
    doc.setFillColor(i % 2 === 0 ? 245 : 255, i % 2 === 0 ? 245 : 255, i % 2 === 0 ? 252 : 255);
    doc.rect(margin, y - 4, W - margin * 2, 8, "F");
    doc.setTextColor(40, 40, 50);
    doc.setFontSize(10);
    doc.text(label, margin + 2, y + 0.5);
    doc.setFont("helvetica", "bold");
    doc.text(`${val} s`, W - margin - 2, y + 0.5, { align: "right" });
    doc.setFont("helvetica", "normal");
    y += 8;
  });

  // Config section
  y += 6;
  doc.setTextColor(100, 100, 120);
  doc.setFontSize(9);
  doc.text("ENGINE & CONFIG", margin, y);
  y += 6;

  const cfgRows = [
    ["Peak power", `${data.config.peak_power_hp.toFixed(1)} hp`],
    ["Peak torque", `${data.config.peak_torque_nm.toFixed(1)} Nm`],
    ["Total mass", `${data.config.total_mass_kg.toFixed(1)} kg`],
    ["Displacement", data.config.displacement_cc ? `${data.config.displacement_cc} cc` : "—"],
    ["Redline", data.config.redline_rpm ? `${data.config.redline_rpm.toLocaleString()} rpm` : "—"],
    ["Gears", String(data.config.gear_count)],
    ["Drag coefficient (Cd)", data.config.cd?.toFixed(3) ?? "—"],
  ];
  cfgRows.forEach(([label, val], i) => {
    doc.setFillColor(i % 2 === 0 ? 245 : 255, i % 2 === 0 ? 245 : 255, i % 2 === 0 ? 252 : 255);
    doc.rect(margin, y - 4, W - margin * 2, 8, "F");
    doc.setTextColor(40, 40, 50);
    doc.setFontSize(10);
    doc.text(label, margin + 2, y + 0.5);
    doc.setFont("helvetica", "bold");
    doc.text(val, W - margin - 2, y + 0.5, { align: "right" });
    doc.setFont("helvetica", "normal");
    y += 8;
  });

  // Footer
  doc.setFillColor(240, 240, 248);
  doc.rect(0, 277, W, 20, "F");
  doc.setTextColor(130, 130, 150);
  doc.setFontSize(8);
  doc.text(
    `Generated by MotoQuant Pro · ${new Date().toLocaleString()} · motoquant.in`,
    margin,
    287,
  );

  const filename = `motoquant_${data.bike.manufacturer}_${data.bike.model}_${data.et.toFixed(3)}s.pdf`
    .replace(/\s+/g, "_");
  doc.save(filename);
}

export function SimulatePage() {
  const { displaySpeed, displayTorque, speedUnit, torqueUnit, defaultVenueId, useAdaptiveDt: defaultAdaptive } = useSettings();

  const [bike, setBike] = useState<BikeSummary | null>(null);
  const [venueId, setVenueId] = useState<number | null>(defaultVenueId);
  const [riderMass, setRiderMass] = useState(75);
  const [powerBoost, setPowerBoost] = useState(0);
  const [massDelta, setMassDelta] = useState(0);
  const [adaptive, setAdaptive] = useState(defaultAdaptive);
  const [savedRunId, setSavedRunId] = useState<number | null>(null);
  const [exporting, setExporting] = useState(false);

  const venues = useVenues();
  const sim = useSimulate();
  const save = useSaveRun();
  const runRef = useRef<() => void>(() => {});

  const canRun = bike != null && !sim.isPending;
  const result = sim.data;

  const onRun = useCallback(() => {
    if (!bike) return;
    setSavedRunId(null);
    sim.mutate({
      bike_id: bike.id,
      venue_id: venueId ?? undefined,
      rider_mass_kg: riderMass,
      power_boost_pct: powerBoost,
      mass_delta_kg: massDelta,
      use_adaptive_dt: adaptive,
    });
  }, [bike, venueId, riderMass, powerBoost, massDelta, adaptive, sim]);

  // Keep ref current so keyboard shortcut can call it.
  runRef.current = onRun;

  useEffect(() => {
    if (sim.isPending) setSavedRunId(null);
  }, [sim.isPending]);

  const onSave = useCallback(() => {
    if (!result || !bike) return;
    save.mutate(
      {
        bike_id: bike.id,
        venue_id: venueId,
        et_quarter_s: result.et_quarter_s,
        trap_speed_kmh: result.trap_speed_kmh,
        et_60ft_s: result.splits["60ft_s"],
        et_eighth_s: result.splits["660ft_s"],
        et_1000ft_s: result.splits["1000ft_s"],
      },
      {
        onSuccess: (data) => {
          setSavedRunId(data.run_id);
          toast.success(`Run #${data.run_id} saved to history`);
        },
        onError: (err) => {
          toast.error(`Save failed: ${err.message}`);
        },
      },
    );
  }, [result, bike, venueId, save]);

  const onExport = useCallback(async () => {
    if (!result || !bike) return;
    setExporting(true);
    try {
      await exportSimPdf({
        bike: result.bike,
        et: result.et_quarter_s,
        trap: result.trap_speed_kmh,
        splits: result.splits as unknown as Record<string, number>,
        config: result.config,
      });
      toast.success("PDF exported");
    } catch (err) {
      toast.error("PDF export failed");
      console.error(err);
    } finally {
      setExporting(false);
    }
  }, [result, bike]);

  // Page-level keyboard shortcuts: r = rerun, s = save, e = export
  useEffect(() => {
    const handler = (e: KeyboardEvent) => {
      const tag = (e.target as HTMLElement)?.tagName?.toLowerCase();
      if (tag === "input" || tag === "textarea" || tag === "select") return;
      if (e.key === "r" && canRun) runRef.current();
      if (e.key === "s" && result && !save.isPending) onSave();
      if (e.key === "e" && result && !exporting) onExport();
    };
    window.addEventListener("keydown", handler);
    return () => window.removeEventListener("keydown", handler);
  }, [canRun, result, save.isPending, exporting, onSave, onExport]);

  return (
    <div className="max-w-6xl mx-auto space-y-6">
      <header>
        <h1 className="text-2xl font-semibold">Simulate a pass</h1>
        <p className="text-sm text-carbon-400 mt-1">
          Pick a bike, tune the rider and mods, hit run. Full quarter-mile physics (RK4, 15
          sub-models). Press <kbd className="font-mono bg-carbon-800 px-1 rounded text-xs">r</kbd> to rerun.
        </p>
      </header>

      <OfflineBanner />

      {/* Config form */}
      <section className="card p-5 space-y-4">
        <div>
          <label className="block text-xs uppercase tracking-wider text-carbon-500 mb-2" htmlFor="bike-picker">
            Bike
          </label>
          <BikePicker value={bike?.id ?? null} onChange={(_, summary) => setBike(summary)} />
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-4">
          <div>
            <label className="block text-xs uppercase tracking-wider text-carbon-500 mb-2" htmlFor="venue-select">
              Venue
            </label>
            <select
              id="venue-select"
              className="input"
              value={venueId ?? ""}
              onChange={(e) => setVenueId(e.target.value ? Number(e.target.value) : null)}
            >
              <option value="">ISA default (sea level, 15 °C)</option>
              {venues.data?.venues.map((v) => (
                <option key={v.id} value={v.id}>
                  {v.name} — {v.country} ({v.altitude_m ?? 0} m)
                </option>
              ))}
            </select>
          </div>

          <Slider label="Rider mass" unit="kg" min={50} max={130} step={1} value={riderMass} onChange={setRiderMass} />
          <Slider label="Power boost" unit="%" min={-20} max={40} step={1} value={powerBoost} onChange={setPowerBoost} />
          <Slider label="Mass change" unit="kg" min={-25} max={25} step={0.5} value={massDelta} onChange={setMassDelta} />

          <label className="flex items-center gap-2 self-end text-sm text-carbon-300 cursor-pointer">
            <input
              type="checkbox"
              checked={adaptive}
              onChange={(e) => setAdaptive(e.target.checked)}
              className="accent-signal-500 focus-visible:outline-2 focus-visible:outline-signal-500"
            />
            Adaptive RK4 (smoother)
          </label>

          <div className="self-end">
            <button
              disabled={!canRun}
              onClick={onRun}
              className="btn btn-primary w-full justify-center focus-visible:outline-2 focus-visible:outline-signal-300"
              aria-label="Run quarter-mile simulation"
              title="Run (r)"
            >
              {sim.isPending ? (
                <><Loader2 className="w-4 h-4 animate-spin" aria-hidden="true" /> Simulating…</>
              ) : (
                <><Play className="w-4 h-4" aria-hidden="true" /> Run quarter-mile</>
              )}
            </button>
          </div>
        </div>
      </section>

      {/* Error */}
      {sim.isError && (
        <div className="card p-4 border-stop-500/40 bg-stop-500/5 flex gap-3" role="alert">
          <AlertTriangle className="w-5 h-5 text-stop-500 shrink-0 mt-0.5" aria-hidden="true" />
          <div>
            <div className="font-medium text-stop-500">Simulation failed</div>
            <div className="text-xs text-carbon-400 mt-1">
              {sim.error?.message || "Unknown error — check that the backend is running."}
            </div>
          </div>
        </div>
      )}

      {/* Loading skeleton */}
      {sim.isPending && !result && (
        <>
          <section className="grid grid-cols-2 md:grid-cols-4 gap-3" aria-label="Loading results">
            {[0,1,2,3].map(i => <SkeletonStatTile key={i} />)}
          </section>
          <SkeletonChartGrid />
        </>
      )}

      {result && (
        <>
          {/* Stat tiles */}
          <section className="grid grid-cols-2 md:grid-cols-4 gap-3" aria-label="Simulation results">
            <StatTile label="Quarter-mile ET" value={result.et_quarter_s.toFixed(3)} unit="s" accent="signal" />
            <StatTile
              label={`Trap speed`}
              value={displaySpeed(result.trap_speed_kmh)}
              unit={speedUnit}
              hint={`${displaySpeed(result.trap_speed_kmh * 0.6214, 1)} mph (alt)`}
            />
            <StatTile label="60 ft" value={result.splits["60ft_s"].toFixed(3)} unit="s" />
            <StatTile label="1/8 mile" value={result.splits["660ft_s"].toFixed(3)} unit="s" />
          </section>

          {/* Action strip */}
          <section className="flex items-center justify-end gap-3 text-sm flex-wrap">
            {result && (
              <button
                onClick={onExport}
                disabled={exporting}
                className="btn btn-ghost inline-flex items-center gap-2 focus-visible:outline-2 focus-visible:outline-signal-500"
                title="Export PDF (e)"
                aria-label="Export simulation report as PDF"
              >
                {exporting ? (
                  <Loader2 className="w-3.5 h-3.5 animate-spin" aria-hidden="true" />
                ) : (
                  <FileDown className="w-3.5 h-3.5" aria-hidden="true" />
                )}
                Export PDF
              </button>
            )}
            {savedRunId != null ? (
              <span className="inline-flex items-center gap-1.5 text-go-500">
                <Check className="w-4 h-4" aria-hidden="true" />
                Saved as run #{savedRunId}
              </span>
            ) : (
              <button
                onClick={onSave}
                disabled={save.isPending || !result}
                className="btn btn-ghost inline-flex items-center gap-2 focus-visible:outline-2 focus-visible:outline-signal-500"
                title="Save run (s)"
                aria-label="Save this run to history"
              >
                {save.isPending ? (
                  <Loader2 className="w-3.5 h-3.5 animate-spin" aria-hidden="true" />
                ) : (
                  <Save className="w-3.5 h-3.5" aria-hidden="true" />
                )}
                Save this run
              </button>
            )}
          </section>

          {/* Config detail */}
          <section className="card p-5">
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-x-8 gap-y-3 text-sm">
              <Detail label="Bike">{result.bike.manufacturer} {result.bike.model}</Detail>
              <Detail label="Power">{result.config.peak_power_hp.toFixed(1)} hp</Detail>
              <Detail label={`Torque (${torqueUnit})`}>{displayTorque(result.config.peak_torque_nm)} {torqueUnit}</Detail>
              <Detail label="Mass (total)">{result.config.total_mass_kg.toFixed(1)} kg</Detail>
              <Detail label="Displacement">{result.config.displacement_cc ?? "—"} cc</Detail>
              <Detail label="Redline">{result.config.redline_rpm?.toLocaleString() ?? "—"} rpm</Detail>
              <Detail label="Gears">{result.config.gear_count}</Detail>
              <Detail label="Cd">{result.config.cd?.toFixed(3) ?? "—"}</Detail>
            </div>
          </section>

          {/* Charts */}
          <section className="grid grid-cols-1 md:grid-cols-2 gap-4" aria-label="Telemetry charts">
            {SIM_CHANNELS.map((ch) => (
              <div key={ch} className="card p-4">
                <SimChart channel={ch} timeseries={result.timeseries} etMark={result.et_quarter_s} />
              </div>
            ))}
          </section>
        </>
      )}
    </div>
  );
}

function Slider({ label, unit, min, max, step, value, onChange }: {
  label: string; unit: string; min: number; max: number; step: number;
  value: number; onChange: (v: number) => void;
}) {
  const id = `slider-${label.replace(/\s+/g, "-").toLowerCase()}`;
  return (
    <div>
      <div className="flex items-baseline justify-between mb-1.5">
        <label htmlFor={id} className="text-xs uppercase tracking-wider text-carbon-500">{label}</label>
        <span className="text-sm font-medium tabular-nums">{value.toFixed(step < 1 ? 1 : 0)} {unit}</span>
      </div>
      <input
        id={id}
        type="range"
        min={min} max={max} step={step} value={value}
        onChange={(e) => onChange(Number(e.target.value))}
        className="w-full accent-signal-500 focus-visible:outline-2 focus-visible:outline-signal-500"
        aria-valuemin={min} aria-valuemax={max} aria-valuenow={value}
        aria-label={`${label}: ${value} ${unit}`}
      />
    </div>
  );
}

function Detail({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div>
      <div className="text-[10px] uppercase tracking-wider text-carbon-500">{label}</div>
      <div className="text-carbon-100 mt-0.5">{children}</div>
    </div>
  );
}
